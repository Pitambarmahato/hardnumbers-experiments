#!/usr/bin/env python3
"""Postgres JSONB vs MongoDB vs Redis vs Valkey behind the same Fastify app.

One database + its app at a time. Load generated by oha in a container on the same Docker network.
Usage: python3 run.py [--quick] [--only postgres,mongo] [--tasks read,write] [--concurrency 10,50]
Writes results/results.json as {"meta": {...}, "results": [...]}.
"""
import argparse, json, subprocess, sys
from pathlib import Path

HERE = Path(__file__).parent
OHA_IMAGE = "ghcr.io/hatoo/oha:1.16.0"
DBS = ["postgres", "mongo", "redis", "valkey"]
CONCURRENCY = [10, 50, 200]
TASKS = {"read": "/read", "write": "/write", "mixed": "/mixed", "incr": "/incr", "query": "/query"}


def sh(*a, check=True):
    return subprocess.run(a, cwd=HERE, check=check, text=True, capture_output=True)


def oha(url, conc, dur):
    cmd = ["docker", "run", "--rm", "--network", "nosql_default", "--cpus", "2", OHA_IMAGE,
           "--output-format", "json", "--no-tui", "-z", f"{dur}s", "-c", str(conc), url]
    return json.loads(sh(*cmd).stdout)


def mem_mib(container):
    used = sh("docker", "stats", "--no-stream", "--format", "{{.MemUsage}}", container).stdout.split("/")[0].strip()
    val = float("".join(c for c in used if c.isdigit() or c == "."))
    return round(val * (1024 if "GiB" in used else 1), 1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true", help="5s runs, 1 repeat, concurrency 50 only")
    ap.add_argument("--only", default=",".join(DBS))
    ap.add_argument("--tasks", default=",".join(TASKS))
    ap.add_argument("--concurrency", default=",".join(map(str, CONCURRENCY)))
    ap.add_argument("--repeats", type=int, default=3)
    ap.add_argument("--duration", type=int, default=20)
    ap.add_argument("--warmup", type=int, default=10)
    ap.add_argument("--out", default=None, help="results file name under results/ (default results.json, or smoke.json with --quick)")
    a = ap.parse_args()
    dur, warm, reps, concs = a.duration, a.warmup, a.repeats, [int(c) for c in a.concurrency.split(",")]
    if a.quick:
        dur, warm, reps, concs = 5, 2, 1, [50]

    sh("docker", "pull", OHA_IMAGE)
    meta = {"oha": sh("docker", "image", "inspect", OHA_IMAGE, "--format", "{{index .RepoDigests 0}}").stdout.strip(),
            "duration_s": dur, "warmup_s": warm, "repeats": reps, "images": {}}
    out, results = HERE / "results" / (a.out or ("smoke.json" if a.quick else "results.json")), []

    for db in a.only.split(","):
        sh("docker", "compose", "up", "-d", "--build", "--wait", f"app-{db}")
        meta["images"][db] = sh("docker", "inspect", f"nosql-{db}-1", "--format", "{{.Config.Image}} {{.Image}}").stdout.strip()
        for task in a.tasks.split(","):
            url = f"http://app-{db}:3000{TASKS[task]}"
            for conc in concs:
                oha(url, conc, warm)  # warmup, discarded
                for rep in range(reps):
                    r = oha(url, conc, dur)
                    s, lp = r["summary"], r["latencyPercentiles"]
                    codes = r.get("statusCodeDistribution", {})
                    ok = sum(v for k, v in codes.items() if k.startswith("2"))
                    total = sum(codes.values()) + sum(v for k, v in r.get("errorDistribution", {}).items() if "deadline" not in k)
                    results.append({
                        "provider": db, "task_id": task, "concurrency": conc, "run": rep + 1,
                        "rps": round(s["requestsPerSec"], 1),
                        "p50_ms": round(lp["p50"] * 1000, 2), "p95_ms": round(lp["p95"] * 1000, 2),
                        "p99_ms": round(lp["p99"] * 1000, 2),
                        "error_rate": round(1 - ok / total, 4) if total else 1.0,
                        "db_mem_mib": mem_mib(f"nosql-{db}-1"), "app_mem_mib": mem_mib(f"nosql-app-{db}-1"),
                    })
                    print(db, task, conc, rep + 1, results[-1]["rps"], "rps", flush=True)
                    out.write_text(json.dumps({"meta": meta, "results": results}, indent=1))
        sh("docker", "compose", "stop", f"app-{db}", db)
    sh("docker", "compose", "down", "-v")
    print("wrote", out)


if __name__ == "__main__":
    sys.exit(main())
